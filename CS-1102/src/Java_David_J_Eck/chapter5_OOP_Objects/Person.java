package Java_David_J_Eck.chapter5_OOP_Objects;

/** Class representing a person who can own a vehicle. */
public class Person {
    String name; // Instance variable to hold the name of the person

    // Constructor to initialize a Person object with a name:
    public Person(String name) {
        this.name = name;   // 'this.name' refers to the instance variable.
    }
}   // end of class Person
